-- ============================================================================
-- מכון קרן רא"ם — תיקון משתמשים ללא פרופיל
-- ----------------------------------------------------------------------------
-- מתי צריך את זה:
--
-- טבלת auth.users חיה בסכימת auth ושורדת כמעט כל פעולה על סכימת public.
-- טבלת profiles חיה ב-public. לכן אם הרצתם מחדש את הסכימה — ובפרט
-- `drop schema public cascade` — המשתמשים נשארו, הפרופילים נמחקו,
-- והטריגר on_auth_user_created לא ירוץ עליהם שוב (הוא פועל רק ביצירת
-- משתמש חדש).
--
-- התסמין: ההתחברות מצליחה, ומיד חוזרים למסך ההתחברות.
-- ============================================================================

-- ----------------------------------------------------------------------------
-- 1. אבחון — מי מאומת אבל בלי פרופיל?
-- ----------------------------------------------------------------------------
select u.id, u.email, 'חסר פרופיל' as status
from auth.users u
left join public.profiles p on p.id = u.id
where p.id is null;

-- ----------------------------------------------------------------------------
-- 2. תיקון גורף — יצירת פרופיל לכל משתמש שאין לו, בתפקיד viewer
-- ----------------------------------------------------------------------------
-- viewer הוא ברירת המחדל הבטוחה: צפייה בלבד, בלי הרשאת כתיבה.
insert into public.profiles (id, full_name, role)
select u.id,
       coalesce(u.raw_user_meta_data->>'full_name', u.email),
       'viewer'
from auth.users u
left join public.profiles p on p.id = u.id
where p.id is null
on conflict (id) do nothing;

-- ----------------------------------------------------------------------------
-- 3. הענקת תפקיד מנהל למשתמש הראשי
-- ----------------------------------------------------------------------------
-- ⚠ החליפו את הכתובת לכתובת שלכם לפני ההרצה.
update public.profiles
set role = 'admin'
where id = (select id from auth.users where email = 'your@email.com');

-- ----------------------------------------------------------------------------
-- 4. אימות
-- ----------------------------------------------------------------------------
select u.email, p.role, p.full_name
from public.profiles p
join auth.users u on u.id = p.id
order by p.role desc, u.email;

