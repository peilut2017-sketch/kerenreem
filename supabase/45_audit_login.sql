-- מדיניות ההוספה הקיימת (audit_log_staff_insert, קובץ 02) גדורה על
-- can_edit() — עורך ומעלה. כניסה למערכת נעשית גם על ידי תפקידים שאינם
-- עורכים (צופה, מלקט, מוכרן), והיומן אמור לתעד את כולן. מדיניות ייעודית
-- וצרה: כל בעל פרופיל צוות רשאי לרשום שורת 'login' על עצמו בלבד —
-- לא שורה אחרת, לא בשם אחר. אין עדכון ואין מחיקה, כמו בשאר היומן.
-- ============================================================================

drop policy if exists audit_log_login_insert on audit_log;
create policy audit_log_login_insert on audit_log
  for insert to authenticated
  with check (
    public.current_user_role() is not null
    and user_id = auth.uid()
    and action = 'login'
  );
