-- התוספת המינימלית שנדרשת: גילוי של סוגי הנתונים החדשים שנאספים (משך
-- צפייה, אתר מפנה ויעד יציאה, פעולות בספרים, סוג מכשיר ומדינה), של דרך
-- האיסוף (בלי עוגיות, בלי IP ובלי מזהה קבוע) ושל תקופת השמירה. תקנון
-- השימוש אינו משתנה — הוא מפנה למדיניות הפרטיות לעניין עיבוד מידע.
--
-- הטקסט נערך בהחלפות ממוקדות (replace) ולא בדריסת הדף כולו: המדיניות
-- ניתנת לעריכה בניהול, ודריסה הייתה מוחקת מילוי של שדות [למילוי]. אם
-- נקודת העיגון כבר נערכה ידנית, ההחלפה אינה משנה דבר (no-op) — במקרה כזה
-- יש להוסיף את הסעיף ידנית (ניהול ← עמודים ← מדיניות פרטיות). הריצה
-- חוזרת בבטחה: אינה מוסיפה את הסעיף פעמיים.
-- ============================================================================

update pages
set body_he = replace(
      body_he,
      '<li>סוג הדפדפן ומערכת ההפעלה, מועד הגישה והעמודים שנצפו — לצורכי אבטחה ותפעול.</li>',
      '<li>סוג הדפדפן ומערכת ההפעלה, מועד הגישה והעמודים שנצפו — לצורכי אבטחה ותפעול.</li>' ||
      '<li><strong>סטטיסטיקת שימוש אנונימית.</strong> משך הצפייה בעמודים, האתר שממנו הגעתם והאתר שאליו עברתם בלחיצה על קישור, פעולות בספרים (שמירה, הוספה לסל, מעבר לרכישה אצל ספק חיצוני), סוג המכשיר והמדינה. הנתונים נאספים ללא עוגיות, ללא שמירת כתובת ה-IP וללא מזהה קבוע: נעשה שימוש במזהה אקראי זמני שנמחק עם סגירת הדפדפן ובגיבוב חד-כיווני יומי שאינו ניתן לשחזור. הם נשמרים עד 13 חודשים ומשמשים לשיפור האתר והתכנים בלבד.</li>'
    ),
    updated_at = now()
where slug = 'privacy'
  and body_he not like '%סטטיסטיקת שימוש אנונימית%';

update pages
set body_he = replace(
      body_he,
      '(עמודים שנצפו, משך ביקור)',
      '(עמודים שנצפו, משך ביקור ופעולות באתר כגון שמירת ספר והוספה לסל)'
    )
where slug = 'privacy';

update pages
set body_he = replace(
      body_he,
      'כל אלה נשמרים בדפדפן שלכם בלבד ואינם נשלחים לשרתי המכון.',
      'כל אלה נשמרים בדפדפן שלכם בלבד ואינם נשלחים לשרתי המכון (למעט רישום אנונימי של עצם שמירת ספר, כמפורט בסעיף 2).'
    )
where slug = 'privacy'
  and body_he not like '%למעט רישום אנונימי של עצם שמירת ספר%';

