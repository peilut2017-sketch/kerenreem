import { notFound } from 'next/navigation';
import { setRequestLocale } from 'next-intl/server';

/**
 * ‏[1.41] כתובת שאינה תואמת שום עמוד באתר.
 *
 * למה הקובץ הזה נחוץ בכלל: ‎[locale]/not-found.tsx נכנס לתמונה רק
 * כשקוד באתר קורא ל-notFound() מתוך מסלול שכן הותאם. כתובת שלא הותאמה
 * לשום מסלול אינה מגיעה אליו — ‏Next מחפש not-found בשורש העץ, ושם אין
 * ‏(לאתר אין app/layout.tsx; לכל קבוצת מסלולים פריסת שורש משלה). לכן
 * ‏/nope הציג את עמוד ברירת המחדל של Next: מסך לבן באנגלית, בלי כותרת,
 * בלי פוטר ובלי סימן שזה אותו אתר. זה מה שדווח כ"עמוד טכני".
 *
 * מסלול catch-all בתוך עץ השפה פותר את זה בלי פריסת שורש חדשה: הכתובת
 * *כן* מותאמת, ולכן notFound() כאן מגיע ל-[locale]/not-found.tsx עם
 * הפריסה המלאה — כותרת, ניווט, פוטר וסרגל נגישות — ועם קוד 404 תקין.
 *
 * הוא אינו מסתיר מסלולים קיימים: ב-Next מקטע סטטי ומקטע דינמי רגיל
 * קודמים ל-catch-all, ולכן רק כתובת שאף אחד מהם לא תפס מגיעה לכאן.
 *
 * ‏**מה שעדיין פתוח**: קוד התשובה. נמדד ב-Next 16.2.12 — notFound()
 * שמטופל ב-[locale]/not-found.tsx מחזיר 200 ולא 404, גם במסלול
 * ‏force-dynamic וגם ב-force-static. לפני התוספת הזו כתובת לא מוכרת
 * קיבלה 404 מעמוד ברירת המחדל של Next (לא ממותג); היום היא מקבלת את
 * העמוד הנכון של האתר עם 200. זו החלפה של פגם אחד באחר, והפגם הנוכחי
 * הוא soft-404 — מנועי חיפוש עלולים לאנדקס עמודי שגיאה. התיקון
 * המלא דורש app/not-found.tsx, ולזה נדרשת פריסת שורש ב-app/, בעוד
 * שכאן לכל קבוצת מסלולים פריסת שורש משלה (שתיהן מרנדרות <html>);
 * זה שינוי מבני שלא נכון לבצע אגב אורחא.
 */
/*
 * ‏force-dynamic, ומסיבה מהותית ולא טכנית: זהו מסלול שכל כתובת שגויה
 * באינטרנט נופלת אליו. תשובת 404 שנשמרת במטמון לכתובת שרירותית היא
 * זיהום מטמון בלי גבול, וגרוע מכך — היא הופכת "העמוד עדיין לא פורסם"
 * ל-404 קבוע גם אחרי שהעמוד פורסם. זה גם מה שמבטיח שקוד התשובה יהיה
 * 404 בפועל ולא 200 של עמוד שנשמר.
 */
export const dynamic = 'force-dynamic';

export default async function CatchAllNotFound({
  params,
}: {
  params: Promise<{ locale: string }>;
}) {
  // ‏setRequestLocale לפני notFound(): בלעדיו עמוד ה-404 מחפש את השפה
  // בבקשה עצמה, וקריאה כזו בזמן רינדור סטטי היא DYNAMIC_SERVER_USAGE —
  // כלומר 500 במקום 404. בדיוק התקלה שתוקנה ב-books/[slug]/not-found.
  const { locale } = await params;
  setRequestLocale(locale);
  notFound();
}
